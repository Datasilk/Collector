/// <summary>
/// Tool that incrementally matures a journal entry as research is collected.
/// Each scraped page produces targeted edit ops (generated by the remote LLM
/// with local fallback) which are validated and applied to the entry's module
/// tree — so the entry evolves page by page instead of being appended blindly.
/// </summary>
public class AddEditJournalEntryTool : IChatTool
{
    private readonly IJournalEntriesRepository _entriesRepository;
    private readonly IJournalsRepository _journalsRepository;
    private readonly IJournalCategoriesRepository _categoriesRepository;
    private readonly OllamaApiClient _ollama;
    private readonly string _ollamaModel;
    private readonly LLMClient _llm;
    private readonly Func<Guid, int, Guid, List<string>, Task>? _onEntrySaved;
    private readonly IJournalSnapshotsRepository? _snapshotsRepository;
    private readonly ISearchEnginesRepository? _searchEnginesRepo;
    private readonly ResearchModuleWriter _writer;
    private readonly List<string> _appliedOps = new();

    /// <summary>Max characters of page content sent to the LLM per edit pass.</summary>
    private const int PageContentBudget = 9000;

    public AddEditJournalEntryTool(
        IJournalEntriesRepository entriesRepository,
        IJournalsRepository journalsRepository,
        IJournalCategoriesRepository categoriesRepository,
        OllamaApiClient ollama,
        string ollamaModel = "llama3.2",
        LLMClient? llm = null,
        Func<Guid, int, Guid, List<string>, Task>? onEntrySaved = null,
        IJournalSnapshotsRepository? snapshotsRepository = null,
        ISearchEnginesRepository? searchEnginesRepo = null)
    {
        _entriesRepository = entriesRepository;
        _journalsRepository = journalsRepository;
        _categoriesRepository = categoriesRepository;
        _ollama = ollama;
        _ollamaModel = ollamaModel;
        _llm = llm ?? new LLMClient(ollama, ollamaModel);
        _onEntrySaved = onEntrySaved;
        _snapshotsRepository = snapshotsRepository;
        _searchEnginesRepo = searchEnginesRepo;
        _writer = new ResearchModuleWriter(_llm);
    }

    public string ToolKey => "add-edit-journal-entry";

    public string Description => "Create or update a journal entry. With scraped pages: integrates research into the entry's module tree. With 'instruction' only: applies a conversational edit (rearrange/add/remove content) to the session's current entry.";

    public bool AvailableToOllama => true;

    public List<ToolParameter> Parameters => new()
    {
        new ToolParameter { Key = "title", DataType = "string", Description = "The title for the journal entry (used for similarity matching)" },
        new ToolParameter { Key = "journalId", DataType = "int", Description = "The ID of the journal to create the entry in (optional)" },
        new ToolParameter { Key = "description", DataType = "string", Description = "Brief description/summary of the entry content" },
        new ToolParameter { Key = "url", DataType = "string", Description = "When set, only integrate the scraped page for this URL" },
        new ToolParameter { Key = "instruction", DataType = "string", Description = "A conversational edit request to apply to the current entry (e.g. 'move the images into a gallery tab')" },
        new ToolParameter { Key = "updateTitle", DataType = "boolean", Description = "Whether to update the title when editing an existing entry" }
    };

    public List<ToolResponseField> ResponseFields => new()
    {
        new ToolResponseField { Key = "entryId", DataType = "guid" },
        new ToolResponseField { Key = "isNew", DataType = "boolean" }
    };

    public async Task Run(
        string userMessage,
        string ragContext,
        List<Dictionary<string, List<string>>> data,
        OnProgress onProgress,
        OnError onError,
        OnComplete onComplete,
        Guid appUserId,
        ExecutionPlan? plan = null,
        int currentStepIndex = -1,
        OnRawRequest? onRawRequest = null,
        OnRawResponse? onRawResponse = null,
        OnSaveChatHistory? onSaveChatHistory = null,
        SendMessage? sendMessage = null,
        CancellationToken cancellationToken = default)
    {
        try
        {
            onProgress(10, "Preparing to update journal entry...");

            var args = plan?.Steps.Count > currentStepIndex && currentStepIndex >= 0
                ? plan.Steps[currentStepIndex].Args
                : new Dictionary<string, object>();

            var filterUrl = args?.GetValueOrDefault("url", "")?.ToString() ?? "";

            // Collect the page items this step should integrate
            var pages = GetPagesToProcess(data, filterUrl);
            var instruction = args?.GetValueOrDefault("instruction", "")?.ToString() ?? "";
            if (pages.Count == 0)
            {
                if (string.IsNullOrWhiteSpace(instruction))
                {
                    onProgress(100, "No new page content to integrate");
                    onComplete("No new content to add to the journal entry");
                    return;
                }
                // Conversational edit — the user's instruction flows through the
                // same edit-op pipeline as a pseudo-page.
                pages.Add(new ScrapedPage
                {
                    IsInstruction = true,
                    Title = "User edit request",
                    Url = "",
                    ContentSections = new List<string> { instruction }
                });
            }

            // Resolve the target entry: session marker → similarity search → create
            var session = GetOrCreateSession(data);
            JournalEntry? entry = null;
            var journalId = 0;

            if (session.EntryId.HasValue)
            {
                entry = _entriesRepository.GetById(session.EntryId.Value);
                journalId = entry?.JournalId ?? session.JournalId;
            }

            if (entry == null)
            {
                if (pages.All(p => p.IsInstruction))
                {
                    onError("No journal entry is associated with this session yet — nothing to edit. Run a research request first, or open a journal entry and start a chat from its toolbar.", null);
                    return;
                }
                var title = args?.GetValueOrDefault("title", "")?.ToString() ?? "";
                var description = args?.GetValueOrDefault("description", "")?.ToString() ?? "";
                var updateTitle = (args?.GetValueOrDefault("updateTitle", "false")?.ToString() ?? "false").ToLower() == "true";

                var cleanedContent = GetPagesText(pages);
                var sourceUrl = pages.FirstOrDefault()?.Url;

                if (string.IsNullOrWhiteSpace(title) || string.IsNullOrWhiteSpace(description))
                {
                    onProgress(15, "Generating title and description from content...");
                    var (generatedTitle, generatedDescription) = await GenerateTitleAndDescriptionAsync(
                        userMessage, cleanedContent, sourceUrl, title, description, cancellationToken);
                    if (string.IsNullOrWhiteSpace(title)) title = generatedTitle;
                    if (string.IsNullOrWhiteSpace(description)) description = generatedDescription;
                }

                var titleEmbedding = await GetEmbeddingAsync(title);

                var journalIdStr = args?.GetValueOrDefault("journalId", "")?.ToString();
                if (int.TryParse(journalIdStr, out var parsedId)) journalId = parsedId;

                onProgress(25, "Searching for existing entries with similar titles...");
                var similarEntry = await FindSimilarEntryAsync(appUserId, journalId, titleEmbedding, onProgress, onError);

                if (similarEntry.HasValue && similarEntry.Value.EntryId.HasValue)
                {
                    entry = _entriesRepository.GetById(similarEntry.Value.EntryId.Value);
                    journalId = entry?.JournalId ?? journalId;
                    if (updateTitle && entry != null && !string.IsNullOrWhiteSpace(title) && title != entry.Title)
                    {
                        entry.Title = title;
                        _entriesRepository.UpdateEmbedding(entry.Id, titleEmbedding);
                    }
                    sendMessage?.Invoke($"Updating existing journal entry '{entry?.Title}' with new research…",
                        entry != null ? $"/journal/{journalId}/entry/{entry.Id}" : null, "View Entry");
                }
                else
                {
                    if (journalId == 0)
                    {
                        onProgress(35, "Selecting best journal...");
                        journalId = await SelectJournalWithOllamaAsync(appUserId, userMessage, ragContext, onProgress, onError, cancellationToken);
                        if (journalId == 0) return;
                    }

                    onProgress(45, $"Creating journal entry '{title}'...");
                    entry = new JournalEntry
                    {
                        JournalId = journalId,
                        Title = title,
                        Description = description,
                        Url = sourceUrl ?? ""
                    };
                    var entryId = _entriesRepository.Add(entry);
                    entry.Id = entryId;
                    _entriesRepository.UpdateEmbedding(entryId, titleEmbedding);
                    sendMessage?.Invoke($"Created journal entry '{title}'",
                        $"/journal/{journalId}/entry/{entryId}", "View Entry");
                }

                if (entry == null)
                {
                    onError("Failed to resolve a journal entry for the research", null);
                    return;
                }

                session.EntryId = entry.Id;
                session.JournalId = journalId;
                session.Persist();
            }

            // Integrate each page into the entry's module tree
            var doc = JournalEntryDocument.Load(entry.Id);

            // Research layer — first pass over an entry without one builds the
            // topic tree from its existing modules (facts extracted via LLM).
            if (doc.Research == null)
            {
                doc.Research = await ResearchBackfill.BuildAsync(
                    doc, entry.Title, ExtractFactListAsync);
            }
            SyncSyntheticRootTitle(doc, entry.Title);

            // Snapshot the pre-edit state once per plan run (tracked via the
            // session marker) so a bad AI edit is one click from rollback. The
            // research path owns the snapshot — instruction edits invoked
            // within the same run skip it via the session flag.
            if (doc.Modules.Count > 0 && !session.SnapshotTaken)
            {
                TakeSnapshot(entry);
                session.SnapshotTaken = true;
                session.Persist();
            }

            // Page accounting for "collecting page N/M" — scrape items are
            // shared across plan steps; 'applied' marks the ones already done.
            var scrapeTypes = new HashSet<string> { "web-scrape", "content", "file-download" };
            var totalPages = data.Count(i => i.TryGetValue("type", out var tl) && tl.Any(t => scrapeTypes.Contains(t)));
            var donePages = data.Count(i => i.TryGetValue("type", out var tl) && tl.Any(t => scrapeTypes.Contains(t)) &&
                i.TryGetValue("applied", out var al) && al.Contains("true"));

            var pageNum = 0;
            var saved = false;

            foreach (var page in pages)
            {
                cancellationToken.ThrowIfCancellationRequested();
                pageNum++;
                var progressBase = 50 + (int)((pageNum - 1) / (double)pages.Count * 45);
                var pageHost = HostOf(page.Url);
                if (page.IsInstruction)
                {
                    onProgress(progressBase, "Applying your requested changes...");
                    sendMessage?.Invoke("Applying your requested changes to the journal entry…", null, null);

                    // If the instruction asks for an image/photo, acquire a real
                    // one through the research downloader path — the LLM must
                    // never invent image URLs (it produced example.com links).
                    try
                    {
                        var assets = await AcquireRequestedImagesAsync(page, entry, onProgress, sendMessage, cancellationToken);
                        if (assets.Count > 0)
                        {
                            page.DownloadedFiles.AddRange(assets.Select(a => a.File));
                            page.ContentSections.Add(
                                "DOWNLOADED MEDIA — these files are already stored inside this entry. " +
                                "To place one, emit an \"image\" module with \"url\" set to the EXACT filename " +
                                "(e.g. {\"type\":\"image\",\"url\":\"" + assets[0].File + "\",\"caption\":\"...\"}) " +
                                "or include the filename in an \"image-gallery\" images array. " +
                                "Never invent image URLs — if no downloaded media is listed, do not add image modules:\n" +
                                string.Join("\n", assets.Select(a => $"  image file \"{a.File}\" — {a.Caption}")));
                        }
                    }
                    catch (Exception ex)
                    {
                        page.ContentSections.Add(
                            "NOTE: an image was requested but could not be downloaded (" + ex.Message +
                            "). Do NOT add image modules with invented URLs — apply the rest of the request without the image.");
                    }

                    // "add a video from <url>" style requests take the media-
                    // placement path — Ollama picks the position over the
                    // semantic skeleton; the ops path handles everything else.
                    var pageInstruction = string.Join("\n", page.ContentSections);
                    if (await TryMediaPlacementAsync(doc, pageInstruction, entry.Id, onRawRequest, onRawResponse, cancellationToken))
                    {
                        page.Applied = true;
                        saved = true;
                        continue;
                    }

                    var applied = await ApplyInstructionEditsAsync(doc, page, onProgress, onRawRequest, onRawResponse, entry.Id, cancellationToken);
                    page.Applied = applied;
                    if (!applied)
                    {
                        sendMessage?.Invoke("I couldn't apply that change — the edit request didn't produce usable operations.", null, null);
                    }
                    saved = true;
                }
                else
                {
                    var ordinal = Math.Max(donePages - pages.Count + pageNum, pageNum);
                    onProgress(progressBase, $"Collecting research from {pageHost} (page {ordinal}/{Math.Max(totalPages, 1)})...");
                    sendMessage?.Invoke($"Collecting research from {pageHost} (page {ordinal}/{Math.Max(totalPages, 1)})…", null, null);

                    await IntegrateResearchPageAsync(doc, page, entry, data, onProgress, onRawRequest, onRawResponse, cancellationToken);
                    page.Applied = true;
                    saved = true;
                }
            }

            if (saved)
            {
                // Provenance: Sources tab inside the first tabs module when one
                // exists; legacy root-level module otherwise.
                if (!_writer.EnsureSourcesTab(doc, doc.Research!))
                    UpsertSourcesModule(doc, data);

                onProgress(95, "Saving journal entry...");
                doc.Save(entry.Id);
                _entriesRepository.UpdateLastModified(entry.Id);

                if (_onEntrySaved != null)
                {
                    try { await _onEntrySaved(entry.Id, journalId, appUserId, new List<string>(_appliedOps)); } catch { /* broadcast is best-effort */ }
                }
            }

            onProgress(100, "Journal entry updated");
            onComplete($"Updated journal entry '{entry.Title}' with content from {pages.Count} page(s)");
            sendMessage?.Invoke($"Updated journal entry '{entry.Title}'",
                $"/journal/{journalId}/entry/{entry.Id}", "View Entry");

            StoreEntryIdInPlan(plan, currentStepIndex, entry.Id);
        }
        catch (OperationCanceledException)
        {
            throw; // user pressed Stop — not a tool error
        }
        catch (Exception ex)
        {
            onError($"Failed to add/edit journal entry: {ex.Message}", ex);
        }
    }

    /// <summary>
    /// RESEARCH path — one scraped page: register its source, extract a flat
    /// fact list via local Ollama, merge into the research object (global
    /// topic/fact dedup), persist facts, then let the module writer regenerate
    /// only the dirty topics. Never emits structural edit ops.
    /// </summary>
    private async Task IntegrateResearchPageAsync(
        JournalEntryDocument doc,
        ScrapedPage page,
        JournalEntry entry,
        List<Dictionary<string, List<string>>> data,
        OnProgress onProgress,
        OnRawRequest? onRawRequest,
        OnRawResponse? onRawResponse,
        CancellationToken cancellationToken = default)
    {
        var research = doc.Research!;
        int? sourceId = null;

        if (!string.IsNullOrWhiteSpace(page.Url))
        {
            var (id, _) = research.RegisterSource(page.Url, page.Title);
            sourceId = id;
            // Re-scrape = replace: drop the facts this source produced before
            // merging the fresh extraction.
            research.RemoveFactsBySource(id);
        }

        var pageText = BuildPageText(page, PageContentBudget);
        List<ExtractedTopic> items = new();
        if (!string.IsNullOrWhiteSpace(pageText))
        {
            var extracted = await ExtractTopicsAsync(entry, research, pageText, onRawRequest, onRawResponse, cancellationToken);
            if (extracted != null) items = extracted;
        }

        var dirty = await research.MergeExtractionAsync(
            items, sourceId ?? 0, texts => _llm.EmbedBatchAsync(texts));

        // Durability ordering — facts persist BEFORE prose generation so a
        // failed module call loses at most that module's HTML.
        doc.Save(entry.Id);

        if (dirty.Count > 0)
        {
            await _writer.WriteDirtyTopicsAsync(doc, research, dirty,
                m => onProgress(60, m), cancellationToken);
        }

        // Deterministic media — scraped images/videos/files become modules
        // beside the topic the page's facts merged into (code-owned, deduped
        // by URL). The writer never touches them.
        AppendPageMedia(doc, page, dirty);
    }

    /// <summary>Flat fact extraction for one scraped page (local Ollama).</summary>
    private async Task<List<ExtractedTopic>?> ExtractTopicsAsync(
        JournalEntry entry,
        ResearchObject research,
        string pageText,
        OnRawRequest? onRawRequest,
        OnRawResponse? onRawResponse,
        CancellationToken cancellationToken = default)
    {
        var system = Prompts.FactExtractionSystem();
        var user = Prompts.FactExtractionUser(entry.Title, research.FormatMarkdown(includeFacts: false), pageText);

        var result = await LLMJson.ParseWithRetryAsync<ExtractionResponse>(
            prompt => _llm.LocalAsync(system, prompt, json: true, cancellationToken,
                onRequest: onRawRequest != null ? (t, p) => onRawRequest("fact-extract", p) : null,
                onResponse: onRawResponse != null ? (t, r) => onRawResponse("fact-extract", r) : null,
                debugType: "fact-extract"),
            user,
            r => r == null ? "response was empty" : (r.Items == null ? "missing \"items\" array" : null),
            maxAttempts: 2);
        return result?.Items;
    }

    /// <summary>Fact-list extraction for backfill — plain facts from a module's
    /// existing text, no categorization needed.</summary>
    private async Task<List<string>> ExtractFactListAsync(string text)
    {
        try
        {
            var system = @"You extract atomic facts from text. Return ONLY valid JSON in this exact format:
{""facts"":[""fact one"",""fact two""]}
Each fact is a single declarative sentence taken from the text. No prose, no markdown fences.";
            var clipped = text.Length > 6000 ? text.Substring(0, 6000) : text;
            var raw = await _llm.LocalAsync(system, "TEXT:\n" + clipped, json: true);
            if (LLMJson.TryParse<FactListResponse>(raw, out var r) && r?.Facts != null)
                return r.Facts.Where(f => !string.IsNullOrWhiteSpace(f)).ToList();
        }
        catch { }
        return new List<string>();
    }

    private static string BuildPageText(ScrapedPage page, int budget)
    {
        var content = $"Title: {page.Title}\n\n" +
                      string.Join("\n", page.Headers.Select(h => $"## {h}")) +
                      (page.Headers.Count > 0 ? "\n" : "") +
                      string.Join("\n\n", page.ContentSections);
        if (content.Length > budget) content = content.Substring(0, budget) + "\n…(truncated)";
        return content;
    }

    /// <summary>
    /// Deterministic media append for scraped pages — images (3), videos (2)
    /// and downloadable files (3), deduped by URL against what's already in
    /// the entry. Placement follows the page's facts: the first dirty topic
    /// bound to a tab gets the media inside that tab; a root-bound topic gets
    /// it right after its module; no merged facts → end of the entry.
    /// </summary>
    private void AppendPageMedia(JournalEntryDocument doc, ScrapedPage page, List<ResearchTopic>? dirty = null)
    {
        var existingUrls = doc.EnumerateModules()
            .SelectMany(m => new[] { m["url"]?.ToString(), m["image"]?.ToString() })
            .Where(u => !string.IsNullOrWhiteSpace(u))
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        // The page's own video (e.g. a YouTube URL the user asked to research)
        // anchors the entry — it goes at the very top, ahead of everything.
        var sourceVideo = GatherResearch.YouTubeHelper.IsYouTubeUrl(page.Url) ? page.Url : null;

        JsonArray container = doc.Modules;
        var insertAt = -1;
        foreach (var t in dirty ?? new List<ResearchTopic>())
        {
            if (t.Archived || string.IsNullOrEmpty(t.ModuleId)) continue;
            var inTab = doc.FindTabByModuleId(t.ModuleId);
            if (inTab != null && inTab.Value.Tab["modules"] is JsonArray tm)
            {
                container = tm;
            }
            else
            {
                for (int i = 0; i < doc.Modules.Count; i++)
                {
                    if (doc.Modules[i] is JsonObject m && m["id"]?.ToString() == t.ModuleId)
                    { insertAt = i + 1; break; }
                }
            }
            break;
        }

        var placed = 0;
        void Place(JsonObject module, bool top = false)
        {
            if (top)
            {
                doc.Modules.Insert(0, module);
                if (container == doc.Modules) insertAt++;
            }
            else if (container == doc.Modules && insertAt >= 0)
            {
                container.Insert(insertAt + placed, module);
            }
            else
            {
                container.Add(module);
            }
            placed++;
        }

        foreach (var img in page.Images.Take(3))
        {
            if (existingUrls.Contains(img)) continue;
            Place(new JsonObject
            {
                ["type"] = "image", ["id"] = JournalEntryDocument.NewModuleId(),
                ["manuallyAdded"] = false, ["url"] = img, ["caption"] = ""
            });
        }
        var videoUrls = (sourceVideo != null ? new[] { sourceVideo } : Enumerable.Empty<string>())
            .Concat(page.Videos)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Take(2);
        foreach (var vid in videoUrls)
        {
            if (existingUrls.Contains(vid)) continue;
            Place(new JsonObject
            {
                ["type"] = "video-player", ["id"] = JournalEntryDocument.NewModuleId(),
                ["manuallyAdded"] = false, ["url"] = vid, ["autoTryAgain"] = true
            }, top: sourceVideo != null && vid.Equals(sourceVideo, StringComparison.OrdinalIgnoreCase));
        }
        foreach (var file in page.Files.Take(3))
        {
            // files arrive as "label|url" pairs from the scraper
            var parts = file.Split('|');
            var url = parts.Length > 1 ? parts[1] : file;
            var name = parts.Length > 1 ? parts[0] : Uri.TryCreate(url, UriKind.Absolute, out var u)
                ? System.IO.Path.GetFileName(u.LocalPath) : url;
            if (existingUrls.Contains(url)) continue;
            Place(new JsonObject
            {
                ["type"] = "file-download", ["id"] = JournalEntryDocument.NewModuleId(),
                ["manuallyAdded"] = false, ["url"] = url, ["filename"] = name
            });
        }
    }

    /// <summary>
    /// Rename the synthetic backfill root topic when the entry title changes
    /// (updateTitle path or a rename since the research was built).
    /// </summary>
    private static void SyncSyntheticRootTitle(JournalEntryDocument doc, string entryTitle)
    {
        var research = doc.Research;
        if (research == null || string.IsNullOrWhiteSpace(entryTitle)) return;
        var synthetic = research.Topics.FirstOrDefault(t => t.Synthetic);
        if (synthetic != null && !synthetic.Topic.Equals(entryTitle, StringComparison.Ordinal))
            synthetic.Topic = entryTitle;
    }

    /// <summary>
    /// Media placement — "add a video from https://…", "add this file" etc.
    /// Ollama picks the position over the semantic skeleton (text-editors
    /// labelled by topic title); the module itself is built deterministically.
    /// Returns true when the request was handled.
    /// </summary>
    private async Task<bool> TryMediaPlacementAsync(
        JournalEntryDocument doc,
        string instruction,
        Guid entryId,
        OnRawRequest? onRawRequest,
        OnRawResponse? onRawResponse,
        CancellationToken cancellationToken = default)
    {
        var urlMatch = Regex.Match(instruction, @"https?://[^\s""'<>]+");
        if (!urlMatch.Success) return false;
        var url = urlMatch.Value.TrimEnd('.', ',', ')', ']');

        var lower = instruction.ToLowerInvariant();
        var isMedia = lower.Contains("video") || lower.Contains("watch") ||
            lower.Contains("pdf") || lower.Contains("file") ||
            lower.Contains("download") || lower.Contains("embed");
        if (!isMedia) return false;

        // Module type is deterministic from the URL/instruction.
        JsonObject module;
        var urlLower = url.ToLowerInvariant();
        if (lower.Contains("video") || lower.Contains("watch") ||
            urlLower.Contains("youtube.com") || urlLower.Contains("youtu.be") ||
            urlLower.Contains("vimeo.com") || urlLower.EndsWith(".mp4") || urlLower.EndsWith(".webm"))
        {
            module = new JsonObject { ["type"] = "video-player", ["url"] = url, ["autoTryAgain"] = true };
        }
        else if (urlLower.EndsWith(".pdf") || lower.Contains("pdf"))
        {
            module = new JsonObject { ["type"] = "pdf-viewer", ["url"] = url };
        }
        else
        {
            var filename = Uri.TryCreate(url, UriKind.Absolute, out var u)
                ? System.IO.Path.GetFileName(u.LocalPath) : url;
            module = new JsonObject { ["type"] = "file-download", ["url"] = url, ["filename"] = filename };
        }

        // Ollama chooses parent + index over the semantic skeleton.
        var placement = await LLMJson.ParseWithRetryAsync<PlacementResponse>(
            prompt => _llm.LocalAsync(Prompts.MediaPlacementSystem(), prompt, json: true, cancellationToken,
                onRequest: onRawRequest != null ? (t, p) => onRawRequest("media-placement", p) : null,
                onResponse: onRawResponse != null ? (t, r) => onRawResponse("media-placement", r) : null,
                debugType: "media-placement"),
            Prompts.MediaPlacementUser(instruction, doc.BuildSemanticMap()),
            r => r == null ? "response was empty" : null,
            maxAttempts: 2);

        var parent = placement?.Parent ?? "root";
        if (doc.ResolveContainer(parent) == null) parent = "root";

        var ops = new JsonObject
        {
            ["ops"] = new JsonArray
            {
                new JsonObject
                {
                    ["op"] = "add",
                    ["parent"] = parent,
                    ["index"] = placement?.Index ?? -1,
                    ["module"] = module
                }
            }
        };
        var errors = doc.ApplyOps(ops);
        _appliedOps.Add($"add:{module["type"]}");
        return errors.Count == 0;
    }

    /// <summary>
    /// Conversational op guardrails — applied to instruction edits BEFORE
    /// ApplyOps: (1) reject ops that would empty the module list, (2) reject
    /// removes of modules not named in the instruction, (3) reject updates
    /// that blank a module. Dropped ops are recorded in _appliedOps.
    /// </summary>
    private void GuardConversationalOps(JsonObject ops, JournalEntryDocument doc, string instruction)
    {
        if (ops["ops"] is not JsonArray arr) return;
        var instructionLower = (instruction ?? "").ToLowerInvariant();
        var instructionWords = new HashSet<string>(
            Regex.Matches(instructionLower, @"[a-z0-9]{4,}").Select(m => m.Value));

        var drop = new List<JsonNode>();

        // (1) collect remove targets; if they cover every module in the entry,
        //     the whole batch of removes is rejected.
        var removeIds = arr.OfType<JsonObject>()
            .Where(o => o["op"]?.ToString() == "remove")
            .Select(o => o["id"]?.ToString() ?? "")
            .Where(id => id.Length > 0)
            .ToHashSet();
        var allIds = doc.EnumerateModules()
            .Select(m => m["id"]?.ToString() ?? "")
            .Where(id => id.Length > 0)
            .ToHashSet();
        var wouldEmpty = allIds.Count > 0 && allIds.IsSubsetOf(removeIds);

        foreach (var node in arr.ToList())
        {
            if (node is not JsonObject op) continue;
            var kind = op["op"]?.ToString() ?? "";

            if (kind == "remove")
            {
                var id = op["id"]?.ToString() ?? "";
                if (wouldEmpty)
                {
                    drop.Add(node);
                    _appliedOps.Add($"dropped:emptying-remove:{id}");
                    continue;
                }

                // (2) removes must name the module — collect every label the
                //     module could be referred to by (type, text fields, tab
                //     titles, bound topic title) and require a word overlap.
                var module = doc.FindModule(id);
                if (module != null)
                {
                    var bound = doc.Research?.FindTopicByModuleId(id)?.Topic ?? "";
                    var haystack = bound + " " +
                        (module["text"]?.ToString() ?? "") + " " +
                        (module["title"]?.ToString() ?? "") + " " +
                        (module["caption"]?.ToString() ?? "") + " " +
                        (module["filename"]?.ToString() ?? "") + " " +
                        (module["originalFilename"]?.ToString() ?? "") + " " +
                        (module["html"]?.ToString() ?? "") + " " +
                        (module["type"]?.ToString() ?? "");
                    if (module["tabs"] is JsonArray tabs)
                        haystack += " " + string.Join(" ",
                            tabs.OfType<JsonObject>().Select(t => t["title"]?.ToString() ?? ""));

                    var labelWords = Regex.Matches(haystack.ToLowerInvariant(), @"[a-z0-9]{4,}")
                        .Select(m => m.Value).ToHashSet();
                    if (!labelWords.Overlaps(instructionWords))
                    {
                        drop.Add(node);
                        _appliedOps.Add($"dropped:unnamed-remove:{id}");
                    }
                }
            }
            else if (kind == "update" && op["set"] is JsonObject set)
            {
                // (3) updates that blank the module's content fields are rejected.
                var blanksContent = new[] { "html", "text", "title", "caption" }
                    .Any(f => set[f] != null && string.IsNullOrWhiteSpace(set[f]!.ToString()));
                if (blanksContent)
                {
                    drop.Add(node);
                    _appliedOps.Add($"dropped:blanking-update:{op["id"]}");
                }
            }
        }

        foreach (var n in drop) arr.Remove(n);
    }

    /// <summary>
    /// Conversational edit path — the remote LLM emits edit ops against the
    /// SEMANTIC skeleton (text-editors labelled by topic title) plus the
    /// compact research context; guardrails run before ops are applied.
    /// Returns true when LLM edits were applied.
    /// </summary>
    private async Task<bool> ApplyInstructionEditsAsync(
        JournalEntryDocument doc,
        ScrapedPage page,
        OnProgress? onProgress,
        OnRawRequest? onRawRequest,
        OnRawResponse? onRawResponse,
        Guid entryId = default,
        CancellationToken cancellationToken = default)
    {
        var instruction = string.Join("\n\n", page.ContentSections);
        if (string.IsNullOrWhiteSpace(instruction)) return false;

        // "bring back the timeline section" — naming an archived topic (in a
        // non-removal context) reactivates it. The writer recreates its
        // module/tab BEFORE the ops call so the semantic map already shows
        // it and the LLM won't add a duplicate.
        await RestoreArchivedTopicsAsync(doc, instruction, entryId, onProgress, cancellationToken);

        var system = Prompts.EntryEditSystem();
        var user = Prompts.InstructionEditUser(
            instruction, doc.BuildSemanticMap(), doc.Research?.FormatCompact() ?? "");

        var ops = await LLMJson.ParseWithRetryAsync<JsonObject>(
            prompt => _llm.RemoteAsync(system, prompt, json: true, cancellationToken,
                onRequest: onRawRequest != null ? (t, p) => onRawRequest("entry-edit", p) : null,
                onResponse: onRawResponse != null ? (t, r) => onRawResponse("entry-edit", r) : null,
                debugType: "entry-edit"),
            user,
            o => o == null ? "response was empty" : (o["ops"] == null ? "missing \"ops\" array" : null),
            maxAttempts: 2);

        if (ops == null)
        {
            // No usable ops — fail honestly rather than appending content the
            // user didn't ask for.
            return false;
        }

        // Strip hallucinated media before applying — the model invents
        // image URLs (example.com/…) when it has no real file to reference.
        SanitizeOps(ops, page, entryId);
        GuardConversationalOps(ops, doc, instruction);
        var errors = doc.ApplyOps(ops);
        var arr = ops["ops"] as JsonArray;
        if (arr != null)
        {
            foreach (var opNode in arr)
            {
                if (opNode is JsonObject o)
                {
                    var kind = o["op"]?.ToString() ?? "?";
                    var target = o["id"]?.ToString()
                        ?? o["module"]?["type"]?.ToString()
                        ?? o["module"]?["id"]?.ToString() ?? "?";
                    _appliedOps.Add($"{kind}:{target}");
                }
            }
        }
        return errors.Count == 0 || errors.Count < (arr?.Count ?? 0);
    }

    private static readonly HashSet<string> RemovalWords = new(StringComparer.OrdinalIgnoreCase)
        { "remove", "delete", "archive", "drop", "hide", "rid", "cut", "erase", "eliminate" };

    /// <summary>
    /// Conversational un-archive — when the instruction names an archived
    /// topic and isn't asking to remove it, the topic goes back to active and
    /// the writer recreates its module/tab in place ("bring back the
    /// timeline section"). Facts were kept all along; only structure is
    /// rebuilt.
    /// </summary>
    private async Task RestoreArchivedTopicsAsync(
        JournalEntryDocument doc, string instruction, Guid entryId, OnProgress? onProgress,
        CancellationToken cancellationToken = default)
    {
        var research = doc.Research;
        if (research == null) return;
        var norm = ResearchObject.Normalize(instruction);
        var instrWords = norm.Split(' ', StringSplitOptions.RemoveEmptyEntries).ToHashSet();

        var dirty = new List<ResearchTopic>();
        foreach (var t in research.AllTopics().Where(t => t.Archived))
        {
            var titleNorm = ResearchObject.Normalize(t.Topic);
            if (titleNorm.Length < 3) continue;
            var titleWords = titleNorm.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            if (!titleWords.All(w => instrWords.Contains(w))) continue;
            if (IsRemovalTarget(norm, titleNorm)) continue;
            research.SetArchived(t, false);
            dirty.Add(t);
        }

        if (dirty.Count == 0) return;
        doc.Save(entryId);
        await _writer.WriteDirtyTopicsAsync(doc, research, dirty,
            m => onProgress?.Invoke(60, m), cancellationToken);
    }

    /// <summary>Is the named topic the object of a removal verb? Checks the
    /// four words preceding the title in the normalized instruction; when the
    /// title isn't a contiguous match, any removal keyword at all is treated
    /// conservatively as a removal.</summary>
    private static bool IsRemovalTarget(string normInstruction, string normTitle)
    {
        var idx = normInstruction.IndexOf(normTitle, StringComparison.Ordinal);
        if (idx < 0)
        {
            return normInstruction.Split(' ', StringSplitOptions.RemoveEmptyEntries)
                .Any(RemovalWords.Contains);
        }
        var before = normInstruction.Substring(0, idx)
            .Split(' ', StringSplitOptions.RemoveEmptyEntries);
        return before.Skip(Math.Max(0, before.Length - 4)).Any(RemovalWords.Contains);
    }

