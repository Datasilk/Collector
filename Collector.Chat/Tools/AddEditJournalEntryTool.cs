    /// <summary>Readable text flattened out of a parser dump — summary,
    /// section headings, block text and list items. Used for the relevance
    /// gate and detail logs; the dump is the page's only content source.</summary>
    private static string ParsedJsonToText(string? parsedJson)
    {
        if (string.IsNullOrWhiteSpace(parsedJson)) return "";
        try
        {
            if (ParseModelJson(parsedJson) is not { } root) return "";
            var sb = new StringBuilder();
            var summary = root["summary"]?.ToString();
            if (!string.IsNullOrWhiteSpace(summary)) sb.AppendLine(summary);
            if (root["sections"] is JsonArray sections)
                foreach (var s in sections)
                {
                    if (s is not JsonObject so) continue;
                    var heading = so["heading"]?.ToString();
                    if (!string.IsNullOrWhiteSpace(heading)) sb.AppendLine("## " + heading);
                    if (so["blocks"] is JsonArray blocks)
                        foreach (var b in blocks)
                        {
                            if (b is not JsonObject bo) continue;
                            var text = bo["text"]?.ToString();
                            if (!string.IsNullOrWhiteSpace(text)) sb.AppendLine(text);
                            if (bo["items"] is JsonArray items)
                                foreach (var i in items)
                                {
                                    var it = i is JsonObject io ? io["text"]?.ToString() : i?.ToString();
                                    if (!string.IsNullOrWhiteSpace(it)) sb.AppendLine("- " + it);
                                }
                        }
                }
            return sb.ToString();
        }
        catch { return ""; }
    }

    private static string BuildPageText(ScrapedPage page, int budget)
    {
        ChatDetailLog.Fn("add-edit-journal-entry", "BuildPageText");
        var parsed = ParsedJsonToText(page.ParsedJson);
        var content = $"Title: {page.Title}\n\n" +
            (string.IsNullOrWhiteSpace(parsed) ? string.Join("\n\n", page.ContentSections) : parsed);
        if (content.Length > budget) content = content.Substring(0, budget) + "\n…(truncated)";
        return content;
    }

    /// <summary>
    /// Deterministic media append for scraped pages — images (3), videos (2)
    /// and downloadable files (3), deduped by URL against what's already in
    /// the entry. Placement follows the page's facts: the first dirty topic
    /// bound to a tab gets the media inside that tab; a root-bound topic gets
    /// it right after its module; no merged facts → end of the entry.
    /// </summary>
    private void AppendPageMedia(JournalEntryDocument doc, ScrapedPage page, List<ResearchTopic>? dirty = null)
    {
        ChatDetailLog.Fn("add-edit-journal-entry", "AppendPageMedia");
        var existingUrls = doc.EnumerateModules()
            .SelectMany(m => new[] { m["url"]?.ToString(), m["image"]?.ToString() }
                .Concat((m["images"] as JsonArray ?? new JsonArray())
                    .Select(i => i is JsonObject io ? io["url"]?.ToString() : i?.ToString())))
            .Where(u => !string.IsNullOrWhiteSpace(u))
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        // The page's own video (e.g. a YouTube URL the user asked to research)
        // anchors the entry — it goes at the very top, ahead of everything.
        var sourceVideo = GatherResearch.YouTubeHelper.IsYouTubeUrl(page.Url) ? page.Url : null;

        JsonArray container = doc.Modules;
        var insertAt = -1;
        foreach (var t in dirty ?? new List<ResearchTopic>())
        {
            if (t.Archived || string.IsNullOrEmpty(t.ModuleId)) continue;
            var inTab = doc.FindTabByModuleId(t.ModuleId);
            if (inTab != null && inTab.Value.Tab["modules"] is JsonArray tm)
            {
                container = tm;
            }
            else
            {
                for (int i = 0; i < doc.Modules.Count; i++)
                {
                    if (doc.Modules[i] is JsonObject m && m["id"]?.ToString() == t.ModuleId)
                    { insertAt = i + 1; break; }
                }
            }
            break;
        }

        var placed = 0;
        void Place(JsonObject module, bool top = false)
        {
            if (top)
            {
                doc.Modules.Insert(0, module);
                if (container == doc.Modules) insertAt++;
            }
            else if (container == doc.Modules && insertAt >= 0)
            {
                container.Insert(insertAt + placed, module);
            }
            else
            {
                container.Add(module);
            }
            placed++;
        }

        // Images are placed by the research content pipeline (galleries per
        // topic) — this pass handles only videos and downloadable files.
        var videoUrls = (sourceVideo != null ? new[] { sourceVideo } : Enumerable.Empty<string>())
            .Concat(page.Videos)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Take(2);
        foreach (var vid in videoUrls)
        {
            if (existingUrls.Contains(vid)) continue;
            Place(new JsonObject
            {
                ["type"] = "video-player", ["id"] = JournalEntryDocument.NewModuleId(),
                ["manuallyAdded"] = false, ["url"] = vid, ["autoTryAgain"] = true
            }, top: sourceVideo != null && vid.Equals(sourceVideo, StringComparison.OrdinalIgnoreCase));
        }
        foreach (var file in page.Files.Take(3))
        {
            // files arrive as "label|url" pairs from the scraper
            var parts = file.Split('|');
            var url = parts.Length > 1 ? parts[1] : file;
            var name = parts.Length > 1 ? parts[0] : Uri.TryCreate(url, UriKind.Absolute, out var u)
                ? System.IO.Path.GetFileName(u.LocalPath) : url;
            if (existingUrls.Contains(url)) continue;
            Place(new JsonObject
            {
                ["type"] = "file-download", ["id"] = JournalEntryDocument.NewModuleId(),
                ["manuallyAdded"] = false, ["url"] = url, ["filename"] = name
            });
        }
    }

    /// <summary>
    /// Rename the synthetic backfill root topic when the entry title changes
    /// (updateTitle path or a rename since the research was built).
    /// </summary>
    private static void SyncSyntheticRootTitle(JournalEntryDocument doc, string entryTitle)
    {
        var research = doc.Research;
        if (research == null || string.IsNullOrWhiteSpace(entryTitle)) return;
        var synthetic = research.Topics.FirstOrDefault(t => t.Synthetic);
        if (synthetic != null && !synthetic.Topic.Equals(entryTitle, StringComparison.Ordinal))
            synthetic.Topic = entryTitle;
    }

    /// <summary>
    /// Media placement — "add a video from https://…", "add this file" etc.
    /// Ollama picks the position over the semantic skeleton (text-editors
    /// labelled by topic title); the module itself is built deterministically.
    /// Returns true when the request was handled.
    /// </summary>
    private async Task<bool> TryMediaPlacementAsync(
        JournalEntryDocument doc,
        string instruction,
        Guid entryId,
        OnRawRequest? onRawRequest,
        OnRawResponse? onRawResponse,
        CancellationToken cancellationToken = default)
    {
        var urlMatch = Regex.Match(instruction, @"https?://[^\s""'<>]+");
        if (!urlMatch.Success) return false;
        var url = urlMatch.Value.TrimEnd('.', ',', ')', ']');

        var lower = instruction.ToLowerInvariant();
        var isMedia = lower.Contains("video") || lower.Contains("watch") ||
            lower.Contains("pdf") || lower.Contains("file") ||
            lower.Contains("download") || lower.Contains("embed");
        if (!isMedia) return false;

        // Module type is deterministic from the URL/instruction.
        JsonObject module;
        var urlLower = url.ToLowerInvariant();
        if (lower.Contains("video") || lower.Contains("watch") ||
            urlLower.Contains("youtube.com") || urlLower.Contains("youtu.be") ||
            urlLower.Contains("vimeo.com") || urlLower.EndsWith(".mp4") || urlLower.EndsWith(".webm"))
        {
            module = new JsonObject { ["type"] = "video-player", ["url"] = url, ["autoTryAgain"] = true };
        }
        else if (urlLower.EndsWith(".pdf") || lower.Contains("pdf"))
        {
            module = new JsonObject { ["type"] = "pdf-viewer", ["url"] = url };
        }
        else
        {
            var filename = Uri.TryCreate(url, UriKind.Absolute, out var u)
                ? System.IO.Path.GetFileName(u.LocalPath) : url;
            module = new JsonObject { ["type"] = "file-download", ["url"] = url, ["filename"] = filename };
        }

        // Ollama chooses parent + index over the semantic skeleton.
        var placement = await LLMJson.ParseWithRetryAsync<PlacementResponse>(
            prompt => _llm.LocalAsync(Prompts.MediaPlacementSystem(), prompt, json: true, cancellationToken,
                onRequest: onRawRequest != null ? (t, p) => onRawRequest("media-placement", p) : null,
                onResponse: onRawResponse != null ? (t, r) => onRawResponse("media-placement", r) : null,
                debugType: "media-placement"),
            Prompts.MediaPlacementUser(instruction, doc.BuildSemanticMap()),
            r => r == null ? "response was empty" : null,
            maxAttempts: 2);

        var parent = placement?.Parent ?? "root";
        if (doc.ResolveContainer(parent) == null) parent = "root";

        var ops = new JsonObject
        {
            ["ops"] = new JsonArray
            {
                new JsonObject
                {
                    ["op"] = "add",
                    ["parent"] = parent,
                    ["index"] = placement?.Index ?? -1,
                    ["module"] = module
                }
            }
        };
        var errors = doc.ApplyOps(ops);
        _writer.PinSourcesLast(doc);
        _appliedOps.Add($"add:{module["type"]}");
        return errors.Count == 0;
    }

    /// <summary>
    /// Conversational op guardrails — applied to instruction edits BEFORE
    /// ApplyOps: (1) reject ops that would empty the module list, (2) reject
    /// removes of modules not named in the instruction, (3) reject updates
    /// that blank a module. Dropped ops are recorded in _appliedOps.
    /// </summary>
    private void GuardConversationalOps(JsonObject ops, JournalEntryDocument doc, string instruction)
    {
        if (ops["ops"] is not JsonArray arr) return;
        var instructionLower = (instruction ?? "").ToLowerInvariant();
        var instructionWords = new HashSet<string>(
            Regex.Matches(instructionLower, @"[a-z0-9]{4,}").Select(m => m.Value));

        var drop = new List<JsonNode>();

        // (1) collect remove targets; if they cover every module in the entry,
        //     the whole batch of removes is rejected.
        var removeIds = arr.OfType<JsonObject>()
            .Where(o => o["op"]?.ToString() == "remove")
            .Select(o => o["id"]?.ToString() ?? "")
            .Where(id => id.Length > 0)
            .ToHashSet();
        var allIds = doc.EnumerateModules()
            .Select(m => m["id"]?.ToString() ?? "")
            .Where(id => id.Length > 0)
            .ToHashSet();
        var wouldEmpty = allIds.Count > 0 && allIds.IsSubsetOf(removeIds);

        foreach (var node in arr.ToList())
        {
            if (node is not JsonObject op) continue;
            var kind = op["op"]?.ToString() ?? "";

            if (kind == "remove")
            {
                var id = op["id"]?.ToString() ?? "";
                if (wouldEmpty)
                {
                    drop.Add(node);
                    _appliedOps.Add($"dropped:emptying-remove:{id}");
                    continue;
                }

                // (2) removes must name the module — collect every label the
                //     module could be referred to by (type, text fields, tab
                //     titles, bound topic title) and require a word overlap.
                var module = doc.FindModule(id);
                if (module != null)
                {
                    // (2a) "delete the Legacy section" — when the op targets a
                    //      whole tabs module but the instruction names only
                    //      some of its tabs, retarget to per-tab removes so
                    //      the siblings survive. A tab counts as named when
                    //      every title word appears in the instruction.
                    if ((module["type"]?.ToString() ?? "") == "tabs" &&
                        module["tabs"] is JsonArray modTabs)
                    {
                        var namedTabs = modTabs.OfType<JsonObject>()
                            .Where(t =>
                            {
                                var words = Regex.Matches(
                                    (t["title"]?.ToString() ?? "").ToLowerInvariant(), @"[a-z0-9]{4,}")
                                    .Select(m => m.Value).ToList();
                                return words.Count > 0 && words.All(w => instructionWords.Contains(w));
                            })
                            .ToList();
                        if (namedTabs.Count > 0 && namedTabs.Count < modTabs.Count)
                        {
                            drop.Add(node);
                            foreach (var t in namedTabs)
                            {
                                var tid = t["id"]?.ToString();
                                if (string.IsNullOrEmpty(tid)) continue;
                                arr.Add(new JsonObject { ["op"] = "remove", ["id"] = tid });
                                _appliedOps.Add($"retargeted:tab-remove:{tid}");
                            }
                            continue;
                        }
                    }

                    var bound = doc.Research?.FindTopicByModuleId(id)?.Topic ?? "";
                    var haystack = bound + " " +
                        (module["text"]?.ToString() ?? "") + " " +
                        (module["title"]?.ToString() ?? "") + " " +
                        (module["caption"]?.ToString() ?? "") + " " +
                        (module["filename"]?.ToString() ?? "") + " " +
                        (module["originalFilename"]?.ToString() ?? "") + " " +
                        (module["html"]?.ToString() ?? "") + " " +
                        (module["type"]?.ToString() ?? "");
                    if (module["tabs"] is JsonArray tabs)
                        haystack += " " + string.Join(" ",
                            tabs.OfType<JsonObject>().Select(t => t["title"]?.ToString() ?? ""));

                    var labelWords = Regex.Matches(haystack.ToLowerInvariant(), @"[a-z0-9]{4,}")
                        .Select(m => m.Value).ToHashSet();
                    if (!labelWords.Overlaps(instructionWords))
                    {
                        drop.Add(node);
                        _appliedOps.Add($"dropped:unnamed-remove:{id}");
                    }
                }
            }
            else if (kind == "update" && op["set"] is JsonObject set)
            {
                // (3) updates that blank the module's content fields are rejected.
                var blanksContent = new[] { "html", "text", "title", "caption" }
                    .Any(f => set[f] != null && string.IsNullOrWhiteSpace(set[f]!.ToString()));
                if (blanksContent)
                {
                    drop.Add(node);
                    _appliedOps.Add($"dropped:blanking-update:{op["id"]}");
                }
            }
        }

        foreach (var n in drop) arr.Remove(n);
    }

    /// <summary>
    /// Conversational edit path — the remote LLM emits edit ops against the
    /// SEMANTIC skeleton (text-editors labelled by topic title) plus the
    /// compact research context; guardrails run before ops are applied.
    /// Returns true when LLM edits were applied.
    /// </summary>
    private async Task<bool> ApplyInstructionEditsAsync(
        JournalEntryDocument doc,
        ScrapedPage page,
        OnProgress? onProgress,
        OnRawRequest? onRawRequest,
        OnRawResponse? onRawResponse,
        Guid entryId = default,
        CancellationToken cancellationToken = default)
    {
        var instruction = string.Join("\n\n", page.ContentSections);
        if (string.IsNullOrWhiteSpace(instruction)) return false;

        // "remove all research that came from example.com" — deterministic:
        // strip every content item tagged to the named source, drop the
        // rendered modules, and skip the ops round-trip entirely.
        if (TryRemoveResearchBySource(doc, instruction))
        {
            doc.Save(entryId);
            return true;
        }

        // "move all the images into an image gallery at the top" —
        // deterministic: merge every image across topics into the first
        // topic's gallery, drop the scattered modules, re-render, and pin
        // the gallery to root[0]. The ops model can't reliably orchestrate
        // this global restructure.
        if (TryConsolidateImagesToTop(doc, instruction, out var dirty, out var galleryModuleId))
        {
            await _writer.WriteDirtyTopicsAsync(doc, doc.Research!, dirty,
                m => onProgress?.Invoke(80, m), cancellationToken);
            if (galleryModuleId != null && doc.FindModule(galleryModuleId) != null)
                doc.ApplyOps(new JsonObject
                {
                    ["ops"] = new JsonArray(new JsonObject
                    {
                        ["op"] = "move", ["id"] = galleryModuleId,
                        ["parent"] = "root", ["index"] = 0
                    })
                });
            doc.Save(entryId);
            return true;
        }

        // "bring back the timeline section" — naming an archived topic (in a
        // non-removal context) reactivates it. The writer recreates its
        // module/tab BEFORE the ops call so the semantic map already shows
        // it and the LLM won't add a duplicate.
        await RestoreArchivedTopicsAsync(doc, instruction, entryId, onProgress, cancellationToken);

        var system = Prompts.EntryEditSystem();
        var user = Prompts.InstructionEditUser(
            instruction, doc.BuildSemanticMap(), doc.Research?.FormatCompact() ?? "");

        var ops = await LLMJson.ParseWithRetryAsync<JsonObject>(
            prompt => _llm.RemoteAsync(system, prompt, json: true, cancellationToken,
                onRequest: onRawRequest != null ? (t, p) => onRawRequest("entry-edit", p) : null,
                onResponse: onRawResponse != null ? (t, r) => onRawResponse("entry-edit", r) : null,
                debugType: "entry-edit"),
            user,
            o => o == null ? "response was empty" : (o["ops"] == null ? "missing \"ops\" array" : null),
            maxAttempts: 2);

        if (ops == null)
        {
            // No usable ops — fail honestly rather than appending content the
            // user didn't ask for.
            return false;
        }

        // Strip hallucinated media before applying — the model invents
        // image URLs (example.com/…) when it has no real file to reference.
        SanitizeOps(ops, page, entryId, doc.JournalId);
        GuardConversationalOps(ops, doc, instruction);
        var errors = doc.ApplyOps(ops);
        _writer.PinSourcesLast(doc);
        var arr = ops["ops"] as JsonArray;
        if (arr != null)
        {
            foreach (var opNode in arr)
            {
                if (opNode is JsonObject o)
                {
                    var kind = o["op"]?.ToString() ?? "?";
                    var target = o["id"]?.ToString()
                        ?? o["module"]?["type"]?.ToString()
                        ?? o["module"]?["id"]?.ToString() ?? "?";
                    _appliedOps.Add($"{kind}:{target}");
                }
            }
        }
        return errors.Count == 0 || errors.Count < (arr?.Count ?? 0);
    }

    private static readonly HashSet<string> RemovalWords = new(StringComparer.OrdinalIgnoreCase)
        { "remove", "delete", "archive", "drop", "hide", "rid", "cut", "erase", "eliminate" };

    /// <summary>
    /// "remove all research that came from example.com" — matches registered
    /// sources by URL or domain in a removal instruction and strips every
    /// content item tagged to them via RemoveContentBySource (the same path
    /// re-scrapes use for replace semantics). Rendered modules are removed
    /// through the normal remove op so archive semantics stay consistent.
    /// The source registration itself is kept — the URL remains in the
    /// Sources list as provenance of what was consulted.
    /// </summary>
    private bool TryRemoveResearchBySource(JournalEntryDocument doc, string instruction)
    {
        var research = doc.Research;
        if (research == null || research.Sources.Count == 0) return false;
        var norm = instruction.ToLowerInvariant();
        var words = norm.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        if (!words.Any(RemovalWords.Contains)) return false;

        var indices = new List<int>();
        for (int i = 0; i < research.Sources.Count; i++)
        {
            var url = research.Sources[i].Url ?? "";
            if (url.Length > 0 && norm.Contains(url.ToLowerInvariant()))
            {
                indices.Add(i);
                continue;
            }
            try
            {
                var host = new Uri(url).Host.ToLowerInvariant();
                if (host.StartsWith("www.")) host = host[4..];
                if (host.Length >= 4 && norm.Contains(host)) indices.Add(i);
            }
            catch { }
        }
        if (indices.Count == 0) return false;

        var totalRemoved = 0;
        foreach (var idx in indices.Distinct())
        {
            var moduleIds = research.RemoveContentBySource(idx);
            totalRemoved += moduleIds.Count;
            if (moduleIds.Count == 0) continue;
            var ops = new JsonObject
            {
                ["ops"] = new JsonArray(moduleIds
                    .Select(m => (JsonNode)new JsonObject { ["op"] = "remove", ["id"] = m })
                    .ToArray())
            };
            doc.ApplyOps(ops);
        }
        _appliedOps.Add($"removed {totalRemoved} research item(s) by source");
        ChatDetailLog.Line($"remove-by-source: {indices.Count} source(s), {totalRemoved} content item(s)");
        return true;
    }

    /// <summary>
    /// "move all the images into an image gallery at the top" — collects
    /// every image/image-gallery content item across all topics, merges
    /// them into the first live topic's gallery (AppendGallery dedupes and
    /// reuses the topic's existing gallery item), and returns the moduleIds
    /// of the stripped items plus the merged gallery's moduleId so the
    /// caller can drop the scattered modules and pin the gallery to the top.
    /// </summary>
    private bool TryConsolidateImagesToTop(
        JournalEntryDocument doc, string instruction,
        out List<ResearchTopic> dirty, out string? galleryModuleId)
    {
        dirty = new List<ResearchTopic>();
        galleryModuleId = null;
        var research = doc.Research;
        if (research == null) return false;
        var norm = instruction.ToLowerInvariant();
        var words = Regex.Matches(norm, @"[a-z0-9]{3,}").Select(m => m.Value).ToHashSet();
        var mentionsImages = words.Overlaps(new[] { "image", "images", "picture", "pictures", "photo", "photos" });
        var wantsTop = norm.Contains("top");
        var all = words.Contains("all");
        if (!(mentionsImages && wantsTop && all)) return false;

        var images = new List<(string Url, string? Alt, string? Caption)>();
        var removedModuleIds = new List<string>();
        foreach (var t in research.AllTopics())
        {
            var content = t.Content;
            for (int i = content.Count - 1; i >= 0; i--)
            {
                if (content[i] is not JsonObject item) continue;
                var type = item["type"]?.ToString() ?? "";
                if (type == "image" && !string.IsNullOrWhiteSpace(item["url"]?.ToString()))
                {
                    images.Add((item["url"]!.ToString(),
                        item["alt_text"]?.ToString() ?? item["alt"]?.ToString(),
                        item["caption"]?.ToString()));
                }
                else if (type == "image-gallery" && item["items"] is JsonArray imgs)
                {
                    foreach (var im in imgs)
                        if (im is JsonObject io && !string.IsNullOrWhiteSpace(io["url"]?.ToString()))
                            images.Add((io["url"]!.ToString(),
                                io["alt_text"]?.ToString(), io["caption"]?.ToString()));
                }
                else continue;
                if (item["moduleId"]?.ToString() is { Length: > 0 } mid)
                    removedModuleIds.Add(mid);
                content.RemoveAt(i);
                if (!dirty.Any(d => ReferenceEquals(d.Node, t.Node))) dirty.Add(t);
            }
        }
        if (images.Count == 0) return false;

        var target = research.Topics.FirstOrDefault(t => !t.Archived)
            ?? research.Topics.FirstOrDefault();
        if (target == null) return false;
        research.AppendGallery(target, images, null);
        if (!dirty.Any(d => ReferenceEquals(d.Node, target.Node))) dirty.Add(target);

        if (removedModuleIds.Count > 0)
            doc.ApplyOps(new JsonObject
            {
                ["ops"] = new JsonArray(removedModuleIds
                    .Select(m => (JsonNode)new JsonObject { ["op"] = "remove", ["id"] = m })
                    .ToArray())
            });

        galleryModuleId = target.Content.OfType<JsonObject>()
            .FirstOrDefault(c => c["type"]?.ToString() == "image-gallery")
            ?["moduleId"]?.ToString();
        _appliedOps.Add($"consolidated {images.Count} image(s) into top gallery");
        ChatDetailLog.Line($"image-consolidate: {images.Count} image(s), {removedModuleIds.Count} module(s) removed");
        return true;
    }

    /// <summary>
    /// Conversational un-archive — when the instruction names an archived
    /// topic and isn't asking to remove it, the topic goes back to active and
    /// the writer recreates its module/tab in place ("bring back the
    /// timeline section"). Facts were kept all along; only structure is
    /// rebuilt.
    /// </summary>
    private async Task RestoreArchivedTopicsAsync(
        JournalEntryDocument doc, string instruction, Guid entryId, OnProgress? onProgress,
        CancellationToken cancellationToken = default)
    {
        var research = doc.Research;
        if (research == null) return;
        var norm = ResearchObject.Normalize(instruction);
        var instrWords = norm.Split(' ', StringSplitOptions.RemoveEmptyEntries).ToHashSet();

        var dirty = new List<ResearchTopic>();
        foreach (var t in research.AllTopics().Where(t => t.Archived))
        {
            var titleNorm = ResearchObject.Normalize(t.Topic);
            if (titleNorm.Length < 3) continue;
            var titleWords = titleNorm.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            if (!titleWords.All(w => instrWords.Contains(w))) continue;
            if (IsRemovalTarget(norm, titleNorm)) continue;
            research.SetArchived(t, false);
            dirty.Add(t);
        }

        if (dirty.Count == 0) return;
        doc.Save(entryId);
        await _writer.WriteDirtyTopicsAsync(doc, research, dirty,
            m => onProgress?.Invoke(60, m), cancellationToken);
    }

    /// <summary>Is the named topic the object of a removal verb? Checks the
    /// four words preceding the title in the normalized instruction; when the
    /// title isn't a contiguous match, any removal keyword at all is treated
    /// conservatively as a removal.</summary>
    private static bool IsRemovalTarget(string normInstruction, string normTitle)
    {
        var idx = normInstruction.IndexOf(normTitle, StringComparison.Ordinal);
        if (idx < 0)
        {
            return normInstruction.Split(' ', StringSplitOptions.RemoveEmptyEntries)
                .Any(RemovalWords.Contains);
        }
        var before = normInstruction.Substring(0, idx)
            .Split(' ', StringSplitOptions.RemoveEmptyEntries);
        return before.Skip(Math.Max(0, before.Length - 4)).Any(RemovalWords.Contains);
    }

