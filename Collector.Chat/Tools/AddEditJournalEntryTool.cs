            ["type"] = new List<string> { "session-entry" },
            ["entryId"] = new List<string>(),
            ["journalId"] = new List<string>(),
            ["snapshotTaken"] = new List<string>()
        };
        data.Add(marker);
        newSession.Marker = marker;
        return newSession;
    }

