    /// <summary>
    /// Pages this step should integrate: a single page when args carries a url,
    /// otherwise every unprocessed scraped page in the shared data list.
    /// </summary>
    private List<ScrapedPage> GetPagesToProcess(List<Dictionary<string, List<string>>> data, string filterUrl)
    {
        var pages = new List<ScrapedPage>();
        foreach (var item in data)
        {
            if (!item.TryGetValue("type", out var typeList)) continue;
            var type = typeList.FirstOrDefault() ?? "";
            if (type != "web-scrape" && type != "content" && type != "file-download") continue;
            if (item.TryGetValue("applied", out var appliedList) && appliedList.Contains("true")) continue;

            var url = item.TryGetValue("url", out var urlList) ? urlList.FirstOrDefault() ?? "" : "";
            if (!string.IsNullOrEmpty(filterUrl) && !url.Equals(filterUrl, StringComparison.OrdinalIgnoreCase)) continue;

            var page = ScrapedPage.FromDataItem(item, url);
            pages.Add(page);
            item["applied"] = new List<string> { "true" };
        }
        return pages;
    }

    /// <summary>
    /// Find or create the session marker that tracks the research target entry
    /// across plan steps.
    /// </summary>
    private SessionTarget GetOrCreateSession(List<Dictionary<string, List<string>>> data)
    {
        foreach (var item in data)
        {
            if (item.TryGetValue("type", out var typeList) && typeList.Contains("session-entry"))
            {
                var session = new SessionTarget();
                if (item.TryGetValue("entryId", out var idList) && Guid.TryParse(idList.FirstOrDefault(), out var id))
                    session.EntryId = id;
                if (item.TryGetValue("journalId", out var jList) && int.TryParse(jList.FirstOrDefault(), out var j))
                    session.JournalId = j;
                if (item.TryGetValue("snapshotTaken", out var snapList))
                    session.SnapshotTaken = snapList.Contains("true");
                session.Marker = item;
                return session;
            }
        }

        var newSession = new SessionTarget();
        var marker = new Dictionary<string, List<string>>
        {
            ["type"] = new List<string> { "session-entry" },
            ["entryId"] = new List<string>(),
            ["journalId"] = new List<string>(),
            ["snapshotTaken"] = new List<string>()
        };
        data.Add(marker);
        newSession.Marker = marker;
        return newSession;
    }

