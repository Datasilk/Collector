    /// <summary>
    /// Collect (title, url) pairs for every scraped/file page in shared data —
    /// fed to EnsureSourcesModule so pages that never reached research
    /// registration still appear in the Sources list.
    /// </summary>
    private static List<(string Title, string Url)> CollectScrapeSources(List<Dictionary<string, List<string>>> data)
    {
        var sources = new List<(string Title, string Url)>();
        foreach (var item in data)
        {
            if (!item.TryGetValue("type", out var typeList)) continue;
            var type = typeList.FirstOrDefault() ?? "";
            if (type != "web-scrape" && type != "content" && type != "file-download") continue;
            var url = item.TryGetValue("url", out var u) ? u.FirstOrDefault() ?? "" : "";
            if (string.IsNullOrWhiteSpace(url)) continue;
            // Direct image/media asset URLs aren't research sources — a jpg
            // in the bullet list is provenance noise.
            var clean = url.Split('?', '#')[0];
            if (Regex.IsMatch(clean, @"\.(jpe?g|png|gif|webp|svg|bmp|ico|mp[34]|webm|mov|css|js|woff2?)$",
                RegexOptions.IgnoreCase)) continue;
            var title = item.TryGetValue("title", out var t) ? t.FirstOrDefault() ?? url : url;
            if (sources.All(s => !s.Url.Equals(url, StringComparison.OrdinalIgnoreCase)))
                sources.Add((title, url));
        }
        return sources;
    }

    /// <summary>Matches "photo/image/picture/portrait of {subject}" in an edit instruction.</summary>
    private static readonly Regex ImageSubjectRegex = new(
        @"(?:photo|image|picture|portrait|headshot|pic|logo|thumbnail)\s+of\s+(.+?)(?=\s+(?:next\s+to|beside|under|above|below|near|into|in|at|to|for|on|from|with|after|before|that|which)\b|[,.;!?]|$)",
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    private static readonly Regex ImageRequestRegex = new(
        @"\b(photo|image|picture|portrait|headshot|logo|pic|thumbnail)\b",
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    /// <summary>
    /// When an instruction asks for an image, fetch a real one: search the
    /// configured engines for the subject, scrape the top pages through the
    /// shared Charlotte pipeline, pick the best image, download it into the
    /// entry's image folder (with a thumb_), and return it for the edit prompt.
    /// </summary>
    private async Task<List<(string File, string Caption, string Url, string SourcePage)>> AcquireRequestedImagesAsync(
        ScrapedPage page, JournalEntry entry, OnProgress onProgress, SendMessage? sendMessage,
        CancellationToken cancellationToken = default)
    {
        var assets = new List<(string File, string Caption, string Url, string SourcePage)>();
        var instruction = string.Join(" ", page.ContentSections.Take(1));
        if (!ImageRequestRegex.IsMatch(instruction))
            return assets;

        var match = ImageSubjectRegex.Match(instruction);
        var subject = match.Success ? match.Groups[1].Value.Trim().Trim('"', '\'') : "";
        subject = Regex.Replace(subject, @"^(?:a|an|the|of)\s+", "", RegexOptions.IgnoreCase).Trim();

        // Resolve against the entry context — "an image of jensen" on an entry
        // titled "Jensen Huang …" must search "jensen huang", not "jensen".
        subject = await ResolveImageSubjectAsync(instruction, subject, entry, cancellationToken);
        if (string.IsNullOrWhiteSpace(subject))
            return assets;

        sendMessage?.Invoke($"Searching the web for an image of \"{subject}\"…", null, null);
        var found = await SearchHelper.FetchImageAsync(subject, _searchEnginesRepo,
            (p, m) => onProgress(Math.Min(90, p), m),
            msg => onProgress(65, msg),
            prompt => _llm.RemoteAsync(Prompts.ScriptAnalysisSystem(), prompt, json: true, cancellationToken));
        if (found == null)
        {
            sendMessage?.Invoke($"Couldn't find a usable image of \"{subject}\" online.", null, null);
            return assets;
        }

        onProgress(70, "Downloading image…");
        var file = await DownloadAndStoreImageAsync(found.Value.ImageUrl, entry, subject,
            msg => onProgress(65, msg));
        if (file != null)
        {
            assets.Add((file, $"Photo of {subject} (source: {found.Value.SourcePage})",
                found.Value.ImageUrl, found.Value.SourcePage ?? ""));
            sendMessage?.Invoke($"Downloaded an image of \"{subject}\" into the journal entry.", null, null);
        }
        else
        {
            sendMessage?.Invoke($"Found an image of \"{subject}\" but couldn't download it.", null, null);
        }
        return assets;
    }

    /// <summary>
    /// Turn a raw "of X" subject into the phrase the user actually means —
    /// resolves shorthand against the entry title/context via local Ollama.
    /// Falls back to the raw subject (or entry title) on any failure.
    /// </summary>
    private async Task<string> ResolveImageSubjectAsync(string instruction, string rawSubject, JournalEntry entry,
        CancellationToken cancellationToken = default)
    {
        try
        {
            var system = "You resolve image search phrases. Given the user's instruction and the journal entry " +
                "they are editing, return the BEST search phrase for finding the requested image. " +
                "Expand shorthand names using the entry context (e.g. 'jensen' on an entry about " +
                "'Jensen Huang' → 'Jensen Huang'). Reply with ONLY the search phrase — no quotes, no explanation.";
            var user = $"Entry title: {entry?.Title}\nEntry description: {entry?.Description}\n" +
                $"User instruction: {instruction}\nExtracted subject: {rawSubject}\nSearch phrase:";
            var resolved = (await _llm.LocalAsync(system, user, json: false, cancellationToken))?.Trim().Trim('"', '\'').Trim();
            if (!string.IsNullOrWhiteSpace(resolved) && resolved.Length <= 80)
                return resolved;
        }
        catch { }
        return !string.IsNullOrWhiteSpace(rawSubject) ? rawSubject : (entry?.Title ?? "");
    }

    /// <summary>
    /// Download image bytes and store them under
    /// journals/{journalId}/{entryId}/images/, generating the thumb_
    /// derivative the gallery expects.
    /// </summary>
    private async Task<string?> DownloadAndStoreImageAsync(string imageUrl, JournalEntry entry, string subject,
        Action<string>? onDebug = null)
    {
        try
        {
            using var client = new HttpClient { Timeout = TimeSpan.FromSeconds(30) };
            client.DefaultRequestHeaders.Add("User-Agent",
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/139.0.0.0 Safari/537.36");
            var bytes = await client.GetByteArrayAsync(imageUrl);
            onDebug?.Invoke($"Image download: {bytes?.Length ?? 0} bytes from {imageUrl}");
            if (bytes == null || bytes.Length < 1000)
            {
                onDebug?.Invoke("Image download rejected — too small (tracking pixel or icon)");
                return null;
            }

            var ext = Path.GetExtension(imageUrl.Split('?', '#')[0]).ToLowerInvariant();
            var validExts = new[] { ".jpg", ".jpeg", ".png", ".webp", ".gif" };
            if (!validExts.Contains(ext)) ext = ".jpg";

            var slug = Regex.Replace(subject.ToLowerInvariant(), @"[^a-z0-9]+", "-").Trim('-');
            if (slug.Length > 40) slug = slug.Substring(0, 40).TrimEnd('-');
            if (string.IsNullOrEmpty(slug)) slug = "image";
            var fileName = slug + ext;

            Files.SaveFileBytes(Files.Paths.Journal, JournalPaths.ImagePath(entry.JournalId, entry.Id, fileName), bytes);

            // The gallery renders local files via thumb_{file} — generate it
            // so downloaded images work in image-gallery modules too.
            try
            {
                var thumb = Images.CreateThumbnail(bytes, 640, 80);
                if (thumb != null && thumb.Length > 0)
                    Files.SaveFileBytes(Files.Paths.Journal, JournalPaths.ImagePath(entry.JournalId, entry.Id, $"thumb_{fileName}"), thumb);
            }
            catch { /* thumbnail is best-effort */ }

            return fileName;
        }
        catch (Exception ex)
        {
            onDebug?.Invoke($"Image download failed for {imageUrl}: {ex.Message}");
            return null;
        }
    }

    /// <summary>
    /// Drop edit ops that reference images the model invented: remote URLs are
    /// allowed unless they point at known placeholder domains; bare filenames
    /// must be files actually stored inside this entry.
    /// </summary>
    private void SanitizeOps(JsonObject ops, ScrapedPage page, Guid entryId, int journalId)
    {
        if (ops["ops"] is not JsonArray arr) return;
        var entryDir = Path.Combine(Files.GetPath(Files.Paths.Journal), journalId.ToString(), entryId.ToString("N"), "images");
        var toRemove = new List<JsonNode>();

        foreach (var node in arr.ToList())
        {
            if (node is not JsonObject op) continue;
            var module = op["module"] as JsonObject ?? op["set"] as JsonObject;
            if (module == null) continue;
            var type = module["type"]?.ToString();
            var bad = false;

            if (type == "image")
            {
                var url = module["url"]?.ToString() ?? "";
                bad = !IsUsableImageRef(url, page, entryDir);
            }
            else if (type == "image-gallery" && module["images"] is JsonArray imgs)
            {
                for (int i = imgs.Count - 1; i >= 0; i--)
                {
                    var item = imgs[i];
                    var url = item is JsonObject io ? io["url"]?.ToString() ?? "" : item?.ToString() ?? "";
                    if (!IsUsableImageRef(url, page, entryDir)) imgs.RemoveAt(i);
                }
                bad = imgs.Count == 0;
            }

            // Scrub invented <img> tags inside html payloads too
            if (module["html"] is JsonValue v && v.TryGetValue<string>(out var html) && html.Contains("<img"))
            {
                var cleaned = Regex.Replace(html, "<img[^>]*src=\"([^\"]+)\"[^>]*/?>",
                    m => IsUsableImageRef(m.Groups[1].Value, page, entryDir) ? m.Value : "");
                if (cleaned != html) module["html"] = cleaned;
            }

            if (bad)
            {
                toRemove.Add(node);
                _appliedOps.Add("dropped:bad-image-url");
            }
        }

        foreach (var n in toRemove) arr.Remove(n);
    }

    /// <summary>
    /// An image reference is usable if it's a real remote URL (not a
    /// placeholder domain) or a bare filename stored inside this entry.
    /// </summary>
    private static bool IsUsableImageRef(string url, ScrapedPage page, string entryDir)
    {
        if (string.IsNullOrWhiteSpace(url)) return false;
        if (url.StartsWith("http://") || url.StartsWith("https://"))
            return !IsPlaceholderImageUrl(url);
        if (url.StartsWith("data:")) return true;
        // Bare filename — must be a file actually stored in this entry
        if (!url.Contains('/') && !url.Contains('\\') && !url.Contains(".."))
            return page.DownloadedFiles.Contains(url) || File.Exists(Path.Combine(entryDir, url));
        return false;
    }

    private static bool IsPlaceholderImageUrl(string url)
    {
        var lower = url.ToLowerInvariant();
        var bad = new[]
        {
            "example.", "placehold", "via.placeholder", "dummyimage",
            "loremflickr", "fakeimg", "picsum.photos", "lorem.space"
        };
        return bad.Any(lower.Contains);
    }

    /// <summary>
    /// Persist a page's parser-model JSON under
    /// journal-entries/{journalId}/{entryId}/research/{####}.json — the
    /// four-digit filename increments from the highest existing dump.
    /// Returns the filename (e.g. "0001.json"), or null on failure.
    /// </summary>
    private static string? SaveResearchDump(int journalId, Guid entryId, string json, string? rawHtmlStaging = null)
    {
        try
        {
            if (journalId <= 0) return null;
            var folder = JournalEntryDocument.ResearchFolderPath(journalId, entryId);
            var root = Files.GetPath(Files.Paths.Journal);
            var dir = Path.Combine(root, folder);
            Directory.CreateDirectory(dir);
            var next = Directory.EnumerateFiles(dir, "*.json")
                .Select(f => int.TryParse(Path.GetFileNameWithoutExtension(f), out var n) ? n : 0)
                .DefaultIfEmpty(0).Max() + 1;
            var name = $"{next:D4}.json";

            // Pair the staged raw HTML as {####}.html so the parser output
            // can be verified against its exact input.
            if (!string.IsNullOrWhiteSpace(rawHtmlStaging))
            {
                var staged = Path.Combine(root, rawHtmlStaging.Replace('/', Path.DirectorySeparatorChar));
                if (File.Exists(staged))
                {
                    try { File.Move(staged, Path.Combine(dir, $"{next:D4}.html")); }
                    catch { /* keep the staging file; html is diagnostic */ }
                }
            }

            return Files.SaveFile(Files.Paths.Journal, $"{folder}/{name}", json) ? name : null;
        }
        catch { return null; }
    }

