    /// <summary>
    /// One-shot journal selection: the model sees the full category→journal
    /// hierarchy as JSON and picks (or proposes creating) a journal + category
    /// in a single call — replacing the old category-then-journal two-hop.
    /// </summary>
    private async Task<int> AskOllamaForJournalUnifiedAsync(
        List<JournalCategory> categories,
        string userMessage,
        string ragContext,
        Guid appUserId,
        CancellationToken cancellationToken = default)
    {
        var hierarchy = JsonSerializer.Serialize(
            categories.Select(c => new
            {
                category = c.Title,
                id = c.Id,
                journals = c.Journals.Select(j => new { journal = j.Title, id = j.Id }).ToList()
            }),
            new JsonSerializerOptions { WriteIndented = false });

        var systemPrompt = @"You are a helpful assistant that selects or creates the most appropriate journal for a user's content.
You are given a JSON array of journal categories, each with its journals:
[{""category"":""Category Name"",""id"":1,""journals"":[{""journal"":""Journal Name"",""id"":5}]}]

Respond ONLY with a valid JSON object in this exact format:
{
  ""journalId"": 0,
  ""newJournalTitle"": """",
  ""newCategoryId"": 0,
  ""newCategoryTitle"": """"
}

Rules:
- If an existing journal fits (including a journal the user explicitly named), return its id in journalId and leave the other fields empty/zero
- If no journal fits but a journal should be created in an EXISTING category, set journalId to 0, provide newJournalTitle, and set newCategoryId to that category's id
- If a brand new category is needed too, set journalId and newCategoryId to 0 and provide both newJournalTitle and newCategoryTitle
- newJournalTitle/newCategoryTitle should be concise (1-3 words)
- Respond with ONLY the JSON object, no additional text";

        var userPrompt = "Journal categories and journals:\n" + hierarchy +
            "\n\nConversation Context:\n" + ragContext +
            "\n\nUser's Request:\n" + userMessage +
            "\n\nWhich journalId should be used? Output the JSON now.";

        try
        {
            var responseContent = await _llm.LocalAsync(systemPrompt, userPrompt, json: true, cancellationToken);

            if (!LLMJson.TryParse<UnifiedJournalSelectionResponse>(responseContent, out var result) || result == null)
            {
                return FallbackJournal(categories, appUserId);
            }

            // existing journal — validate it actually exists
            if (result.JournalId > 0 &&
                categories.SelectMany(c => c.Journals).Any(j => j.Id == result.JournalId))
            {
                return result.JournalId;
            }

            // new journal requested — resolve its category
            if (!string.IsNullOrWhiteSpace(result.NewJournalTitle))
            {
                JournalCategory? category = null;
                if (result.NewCategoryId > 0)
                    category = categories.FirstOrDefault(c => c.Id == result.NewCategoryId);
                if (category == null && !string.IsNullOrWhiteSpace(result.NewCategoryTitle))
                {
                    var catId = CreateCategory(appUserId, result.NewCategoryTitle.Trim());
                    category = new JournalCategory { Id = catId, AppUserId = appUserId, Title = result.NewCategoryTitle.Trim() };
                }
                category ??= categories.FirstOrDefault()
                             ?? new JournalCategory { Id = CreateCategory(appUserId, "Research"), AppUserId = appUserId };
                return CreateJournal(category, result.NewJournalTitle.Trim());
            }

            return FallbackJournal(categories, appUserId);
        }
        catch
        {
            return FallbackJournal(categories, appUserId);
        }
    }

    private int FallbackJournal(List<JournalCategory> categories, Guid appUserId)
    {
        var first = categories.SelectMany(c => c.Journals).FirstOrDefault();
        if (first != null) return first.Id;
        var category = categories.FirstOrDefault()
                       ?? new JournalCategory { Id = CreateCategory(appUserId, "Research"), AppUserId = appUserId };
        return CreateJournal(category, "Research");
    }

    private class UnifiedJournalSelectionResponse
    {
        [System.Text.Json.Serialization.JsonPropertyName("journalId")]
        public int JournalId { get; set; }
        [System.Text.Json.Serialization.JsonPropertyName("newJournalTitle")]
        public string? NewJournalTitle { get; set; }
        [System.Text.Json.Serialization.JsonPropertyName("newCategoryId")]
        public int NewCategoryId { get; set; }
        [System.Text.Json.Serialization.JsonPropertyName("newCategoryTitle")]
        public string? NewCategoryTitle { get; set; }
    }

    private int CreateCategory(Guid appUserId, string title)
    {
        var newCategory = new JournalCategory
        {
            AppUserId = appUserId,
            Title = title,
            Color = "#4A90D9"
        };
        return _categoriesRepository.Add(newCategory);
    }

    private int CreateJournal(JournalCategory category, string title)
    {
        var newJournal = new Journal
        {
            AppUserId = category.AppUserId,
            CategoryId = category.Id,
            Title = title,
            Color = "#4A90D9"
        };
        return _journalsRepository.Add(newJournal);
    }

    /// <summary>
    /// Generate title and description based on content and user context
    /// </summary>
    private async Task<(string Title, string Description)> GenerateTitleAndDescriptionAsync(
        string userMessage,
        string cleanedContent,
        string? sourceUrl,
        string existingTitle,
        string existingDescription,
        CancellationToken cancellationToken = default)
    {
        try
        {
            var hasContent = !string.IsNullOrWhiteSpace(cleanedContent);
            var contentPreview = hasContent
                ? string.Join(" ", cleanedContent.Split(new[] { ' ', '\n', '\r', '\t' }, StringSplitOptions.RemoveEmptyEntries).Take(500))
                : "(No content available)";

            var urlContext = !string.IsNullOrWhiteSpace(sourceUrl) ? $"\n\nSource URL: {sourceUrl}" : "";
            var userPrompt = $"User's request/question: {userMessage}{urlContext}\n\nAvailable content:\n{contentPreview}\n\n";

            if (!string.IsNullOrWhiteSpace(existingTitle)) userPrompt += $"Existing title (improve if needed): {existingTitle}\n";
            if (!string.IsNullOrWhiteSpace(existingDescription)) userPrompt += $"Existing description (improve if needed): {existingDescription}\n";
            userPrompt += "\nGenerate a title and description for this journal entry. Return ONLY JSON:";

            var parsed = await LLMJson.ParseWithRetryAsync<TitleDescriptionResponse>(
                p => _llm.LocalAsync(Prompts.TitleDescriptionSystem(), p, json: true, cancellationToken),
                userPrompt,
                r => r == null || string.IsNullOrWhiteSpace(r.Title) ? "missing title" : null,
                maxAttempts: 2);

            var title = parsed?.Title?.Trim() ?? "New Entry";
            var description = parsed?.Description?.Trim() ?? "";

            if (string.IsNullOrWhiteSpace(title) || title.Length < 3) title = "New Entry";
            if (title.Length > 100) title = title.Substring(0, 97) + "...";
            if (description.Length > 500) description = description.Substring(0, 497) + "...";

            return (title, description);
        }
        catch
        {
            return ("New Entry", "Journal entry created from web research.");
        }
    }

    private void StoreEntryIdInPlan(ExecutionPlan? plan, int currentStepIndex, Guid entryId)
    {
        if (plan == null || currentStepIndex < 0 || currentStepIndex >= plan.Steps.Count) return;

        var currentStep = plan.Steps[currentStepIndex];
        currentStep.Result ??= new Dictionary<string, object>();
        currentStep.Result["entryId"] = entryId.ToString();
    }



