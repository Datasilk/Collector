    /// <summary>
    /// One scraped page extracted from a shared-data dictionary item.
    /// </summary>
    private class ScrapedPage
    {
        public string Url = "";
        public string Title = "";
        public List<string> Headers = new();
        public List<string> ContentSections = new();
        public List<string> Images = new();
        public List<string> Videos = new();
        public List<string> Files = new();
        public bool Applied;
        public bool IsInstruction;
        /// <summary>Downloadable file (PDF/image/zip), not a text page — skips the relevance gate.</summary>
        public bool IsFile;
        public string PayloadText = "";
        /// <summary>Structured JSON from the HTML parser model (LLM_HtmlParsers).</summary>
        public string? ParsedJson;
        /// <summary>Staging path (under journals/_staging/) for the raw HTML
        /// the parser consumed — moved to research/{####}.html on dump save.</summary>
        public string? RawHtmlFile;
        /// <summary>Filenames downloaded into this entry during instruction edits.</summary>
        public List<string> DownloadedFiles = new();

        public static ScrapedPage FromDataItem(Dictionary<string, List<string>> item, string url)
        {
            var page = new ScrapedPage { Url = url };
            if (item.TryGetValue("title", out var t)) page.Title = t.FirstOrDefault() ?? "";
            if (item.TryGetValue("headers", out var h)) page.Headers = h;
            if (item.TryGetValue("content", out var c)) page.ContentSections = c;
            if (item.TryGetValue("images", out var i)) page.Images = i;
            if (item.TryGetValue("videos", out var v)) page.Videos = v;
            if (item.TryGetValue("files", out var f)) page.Files = f;
            if (item.TryGetValue("parsed", out var pj)) page.ParsedJson = pj.FirstOrDefault();
            if (item.TryGetValue("rawhtml", out var rh)) page.RawHtmlFile = rh.FirstOrDefault();
            return page;
        }

        /// <summary>
        /// Compact payload for the LLM: title/url + content within budget +
        /// media/file lists. Wrapped in untrusted-data delimiters.
        /// </summary>
        public string BuildPayload(int budget)
        {
            var sb = new StringBuilder();
            if (IsInstruction)
            {
                // Conversational edit: the payload is a user instruction to apply
                // (move/remove/update ops), not page content to integrate.
                var text = string.Join("\n\n", ContentSections);
                if (text.Length > budget) text = text.Substring(0, budget);
                sb.AppendLine("USER EDIT REQUEST — apply this change to the journal entry's structure/content. " +
                    "Map the request to ops: \"remove/delete X\" → remove ops on the matching module(s); " +
                    "\"replace/update X\" → update ops carrying the new content; \"move/rearrange X\" → move ops; " +
                    "\"add X\" → add ops. Prefer update/remove/move over adding duplicates of existing content.");
                sb.AppendLine(Prompts.WrapUntrusted(text));
                PayloadText = sb.ToString();
                return PayloadText;
            }
            sb.AppendLine($"Page url: {Url}");

            var parsed = ParsedJsonToText(ParsedJson);
            var content = $"Title: {Title}\n\n" +
                (string.IsNullOrWhiteSpace(parsed) ? string.Join("\n\n", ContentSections) : parsed);
            if (content.Length > budget) content = content.Substring(0, budget) + "\n…(truncated)";
            if (!string.IsNullOrWhiteSpace(content)) sb.AppendLine("Page text:\n" + Prompts.WrapUntrusted(content));

            if (Images.Count > 0) sb.AppendLine("Images: " + string.Join(", ", Images.Take(10)));
            if (Videos.Count > 0) sb.AppendLine("Videos: " + string.Join(", ", Videos.Take(5)));
            if (Files.Count > 0) sb.AppendLine("Downloadable files: " + string.Join(", ", Files.Take(10)));

            PayloadText = sb.ToString();
            return PayloadText;
        }
    }

